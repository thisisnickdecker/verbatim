// Builds dist/: the loadable extension zip and a single Markdown file that
// contains everything (docs, source, tests, examples, verification log) for
// handing to another assistant.
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const pkg = require('../package.json');
fs.mkdirSync(DIST, { recursive: true });

const EXTENSION_FILES = [
  'manifest.json',
  'src/background.js',
  'src/content/run-capture.js',
  'src/platforms/chatgpt.js',
  'src/platforms/registry.js',
  'src/core/html-to-markdown.js',
  'src/core/normalize.js',
  'src/core/completeness.js',
  'src/core/exporters.js',
];
const OTHER_FILES = ['test/fake-chatgpt.js', 'test/capture.test.js', 'package.json', 'scripts/build-handoff.js'];

const zip = path.join(DIST, `conversation-capture-v${pkg.version}.zip`);
fs.rmSync(zip, { force: true });
execSync(`zip -q -r "${zip}" manifest.json src icons README.md`, { cwd: ROOT });

const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const lang = (f) => ({ '.js': 'js', '.json': 'json', '.md': 'markdown' }[path.extname(f)] || '');
const fenced = (f) => {
  const body = read(f);
  const ticks = '`'.repeat(Math.max(3, ...(body.match(/`{3,}/g) || []).map((m) => m.length + 1)));
  return `### \`${f}\`\n\n${ticks}${lang(f)}\n${body.replace(/\n$/, '')}\n${ticks}\n`;
};

const testOutput = execSync('node --test test/capture.test.js 2>&1 || true', { cwd: ROOT, encoding: 'utf8' })
  .split('\n').filter((l) => /^(not )?ok |^# (tests|pass|fail)/.test(l)).join('\n');

const live = fs.existsSync(path.join(ROOT, 'VERIFICATION.md')) ? read('VERIFICATION.md') : '_No live verification log._';

const doc = `# Conversation Capture v${pkg.version}: complete handoff

This one file contains everything about the Conversation Capture Chrome extension: what it is, how to install it, how it was verified, its limitations, example exports, and the full source code. The loadable extension is in \`conversation-capture-v${pkg.version}.zip\` next to this file.

## Contents

1. README (install, use, architecture, schema, privacy, known limitations)
2. Verification log (test results and live run against a real ChatGPT conversation)
3. Example Markdown export
4. Example JSON export
5. Source code (extension)
6. Source code (tests and tooling)

---

# 1. README

${read('README.md').replace(/^# /, '## ').replace(/\n## /g, '\n### ')}

---

# 2. Verification log

## Automated tests (\`npm test\`)

\`\`\`text
${testOutput}
\`\`\`

${live}

---

# 3. Example Markdown export

Generated by the test suite from a synthetic three-turn conversation that exercises code blocks, formatting, citations, writing blocks, images and attachments.

\`\`\`\`\`markdown
${read('examples/example-conversation.md').replace(/\n$/, '')}
\`\`\`\`\`

---

# 4. Example JSON export

\`\`\`json
${read('examples/example-conversation.json').replace(/\n$/, '')}
\`\`\`

---

# 5. Source code: extension

${EXTENSION_FILES.map(fenced).join('\n')}

---

# 6. Source code: tests and tooling

${OTHER_FILES.map(fenced).join('\n')}
`;

fs.writeFileSync(path.join(DIST, 'HANDOFF-FOR-CHATGPT.md'), doc);
console.log('wrote', path.relative(ROOT, zip), 'and dist/HANDOFF-FOR-CHATGPT.md', `(${Math.round(doc.length / 1024)} KB)`);
